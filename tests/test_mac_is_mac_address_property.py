"""Property tests locking ``mac._is_mac_address`` and the MAC normalisers.

``_is_mac_address`` gates whether a target is treated as a MAC address (and so
sent to the vendor API / used for OUI extraction) instead of as a hostname or
IP. A false positive therefore fabricates an OUI from a non-MAC string and
sends it to the API. The previous ``test_is_mac_address_*`` tests only
exercised a handful of fixed examples, so a regression that re-adopted the
lenient ``int(value, 16)`` parsing (which accepts an embedded ``_`` separator,
a leading ``+``/``-`` sign, surrounding whitespace, or non-ASCII digits) would
still pass them.

These tests use an *independent* oracle: a value is a MAC address iff, after
removing the ``:``/``-``/``.`` separators, it is exactly twelve ASCII hex
digits. Valid MACs are built from known octets (so the expected answer is known
by construction), and near-MAC junk is generated by injecting characters that
``int(value, 16)`` tolerates but that are not hex digits.
"""

from __future__ import annotations

import random
import re

import pytest

from ethscan.mac import _extract_oui, _is_mac_address, _normalize_mac_for_api

_PROPERTY_SEED = 20261128
_HEX = "0123456789abcdefABCDEF"
_SEPARATORS = (":", "-", ".", "")
# Characters that ``int(value, 16)`` accepts but that are not ASCII hex digits:
# an underscore group separator, a sign, ASCII / unicode whitespace, and a
# non-ASCII (Arabic-Indic) digit.
_LENIENT_JUNK = ("_", "+", "-", " ", "\t", "\n", "\u00a0", "\u0660")


def _strict_oracle(value: str) -> bool:
    """Independent oracle: twelve ASCII hex digits after separator removal."""
    cleaned = value.replace(":", "").replace("-", "").replace(".", "")
    return re.fullmatch(r"[0-9A-Fa-f]{12}", cleaned) is not None


def _random_mac(rng: random.Random) -> str:
    """Build a random valid MAC address with randomised separators and case."""
    octets = [rng.randint(0, 255) for _ in range(6)]
    sep = rng.choice(_SEPARATORS)
    body = sep.join(
        ("%02X" % o) if rng.random() < 0.5 else ("%02x" % o) for o in octets
    )
    return body


def test_valid_serialisations_are_mac_addresses() -> None:
    """Every random valid MAC, in any separator/case, is recognised."""
    rng = random.Random(_PROPERTY_SEED)
    for _ in range(5000):
        mac = _random_mac(rng)
        assert _is_mac_address(mac) is True
        assert _strict_oracle(mac) is True


def test_near_mac_junk_agrees_with_strict_oracle() -> None:
    """Impl and oracle agree on near-MAC junk (both reject lenient forms)."""
    rng = random.Random(_PROPERTY_SEED + 1)
    for _ in range(20000):
        chars = [
            rng.choice(_LENIENT_JUNK)
            if rng.random() < 0.15
            else rng.choice(_HEX)
            for _ in range(12)
        ]
        candidate = "".join(chars)
        assert _is_mac_address(candidate) is _strict_oracle(candidate)


@pytest.mark.parametrize(
    "value",
    [
        "0_1A2B3C4D5E",
        "+1A2B3C4D5E4",
        "\t4E4473fF5Ad",
        "dcEd0dF5ac3 ",
        "\u0660" * 12,
        "00:1A:2B:3C:4D:5E:8080",
        "001A2B3C4D5E6",
        "GG:1A:2B:3C:4D:5E",
        "",
    ],
)
def test_lenient_forms_are_rejected(value: str) -> None:
    """Regression vectors: lenient / malformed forms must not pass as MACs."""
    assert _is_mac_address(value) is False


def test_normalize_mac_for_api_strips_separators_and_lowercases() -> None:
    """Normalisation yields the bare lower-case hex the OUI API expects."""
    rng = random.Random(_PROPERTY_SEED + 2)
    for _ in range(2000):
        mac = _random_mac(rng)
        expected = mac.replace(":", "").replace("-", "").replace(".", "").lower()
        assert _normalize_mac_for_api(mac) == expected
        assert len(_normalize_mac_for_api(mac)) == 12


def test_extract_oui_is_first_six_hex_digits() -> None:
    """OUI extraction is the first 24 bits, normalised, for any valid MAC."""
    rng = random.Random(_PROPERTY_SEED + 3)
    for _ in range(2000):
        mac = _random_mac(rng)
        cleaned = mac.replace(":", "").replace("-", "").replace(".", "").lower()
        assert _extract_oui(mac) == cleaned[:6]
        assert len(_extract_oui(mac)) == 6